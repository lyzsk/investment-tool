P_FAGE = re.compile(r"\*\*发哥刹车条款（G-1， 10/6 立法）\*\*：[^\n]*?不许无视；")
P_DIR = re.compile(r"\*\*方向归市场，手艺归人格（10/4 用户立法，盲区修复⑤）\*\*：[^\n]*")
P_ROT = re.compile(r"\*\*轮动位置判定（10/4 盲区修复⑥）\*\*：[^\n]*")
P_CHAIN = re.compile(r"(②[^\n]*?选股方向组=必填推导链)：方向→板块→细分概念→大票/小票→个股")
P_POOL = re.compile(r"\*\*双池制取数（10/4 用户立法，盲区修复⑤）\*\*：[^\n]*")
P_EXP = re.compile(r"\*\*扩池提案义务\*\*：[^\n]*\n?")
P_POOLNOTE = re.compile(r"（pool_proposals 仅在覆盖率 WARN 触发时必填，平时可省）")
P_04C = re.compile(r"按 方向→板块→细分→大/小票→个股 每环一行短句")
P_STANCE = re.compile(r"④\*\*今日态度 stance")


def transform(skill, t):
    cfg = M[skill]
    n = {}
    scope_blk = (f"**看哪由本导师决定{MARK}**：方向只在本导师能力圈里找, 取代 10/4\"方向归市场\"立法(对照组保留市场视角作基准)。"
                 f"本导师能力圈(10/15 按{'本人视频/复盘口述正推' if skill in UP else '真实成交逆推: 板块分布/常买票/行业/时段/持仓天数'}): {cfg['scope']}。"
                 "市场主线不在能力圈内=正文写一句\"不碰: xx(不在能力圈)\"即可, **不要为了覆盖主线硬加方向**; 能力圈里今天没机会=directions 写本导师的观察方向, stance 给中立/空。")
    t, n["dir"] = P_DIR.subn(scope_blk, t)
    if skill not in UP:
        t, n["fage"] = P_FAGE.subn("**发哥推演（参考）**：01 摘要里的发哥信号只作参考, 与本导师风格无关可以不回应；", t)
    t, n["rot"] = P_ROT.subn("**轮动位置（可选）**：facts\"轮动位置\"节可作参考, 方向不必逐个标注位置。", t)
    t, n["chain"] = P_CHAIN.subn(lambda m: f"{m.group(1)}（本导师自己的路径{MARK}）：{cfg['chain']}", t)
    if cfg["pick"]:
        t, n["pool"] = P_POOL.subn(f"**取数{MARK}**：方向组个股来源={cfg['pick']}。**能力圈外的方向可以整组不碰**(不必为 02 的每个方向都出候选; 02 也只会给能力圈内的方向)。", t)
        t, n["exp"] = P_EXP.subn("", t)
        t, n["pnote"] = P_POOLNOTE.subn("（本链不做扩池提案, pool_proposals 省略）", t)
    t, n["04c"] = P_04C.subn(f"按本导师推导链（{cfg['chain']}）每环一行短句", t)
    return t, n


def main():
    dry = "--dry" in sys.argv
    BAK.mkdir(parents=True, exist_ok=True)
    for skill in M:
        f = ROOT / "skills" / f"{skill}-skill" / "workflows" / "chain.md"
        t = f.read_text(encoding="utf-8")
        if MARK in t:
            print(f"{skill}: 已改过, 跳过"); continue
        new, n = transform(skill, t)
        need = {"dir": 1, "rot": 1, "chain": 2, "04c": 1}
        if skill not in UP:
            need["fage"] = 1
        if M[skill]["pick"]:
            need.update(pool=2, exp=2, pnote=2)
        bad = {k: (n.get(k, 0), v) for k, v in need.items() if n.get(k, 0) != v}
        print(f"{skill}: 替换计数 {n}" + (f"  ⚠ 与预期不符 {bad}" if bad else "  ✓"))
        if bad or dry:
            continue
        shutil.copy(f, BAK / f"{skill}.chain.md")
        f.write_text(new, encoding="utf-8", newline="")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
